import 'package:breakmate/features/companion/domain/avatar_species.dart';

/// Tunable temperament of one species; every field scales the shared procedural motion in PetBehaviorEngine.
class SpeciesPersonality {
  const SpeciesPersonality({
    this.speed = 1.0,
    this.amplitude = 1.0,
    this.blinkMin = 1.6,
    this.blinkMax = 6.0,
    this.doubleBlink = 0.12,
    this.breathRate = 1.0,
    this.breathDepth = 1.0,
    this.earTwitch = 0.04,
    this.headTilt = 0.03,
    this.bounce = 1.0,
    this.energy = 0.5,
    this.glance = 1.0,
    this.bob = 0.0,
    this.noseTwitch = 0.0,
  });

  /// Timing multiplier for blinks, bobbing and idle timers.
  final double speed;

  /// Size multiplier for idle gaze spread, tilts and bobs.
  final double amplitude;

  /// Seconds between blinks, drawn skewed towards [blinkMin].
  final double blinkMin;
  final double blinkMax;

  /// Chance a blink is followed by a quick second one.
  final double doubleBlink;

  final double breathRate;
  final double breathDepth;

  /// Events per second while awake and idle.
  final double earTwitch;
  final double headTilt;
  final double noseTwitch;

  /// Multiplier for hop/bounce impulses.
  final double bounce;

  /// 0 sluggish .. 1 hyper; scales how often idle actions fire.
  final double energy;

  /// Eye-wander frequency multiplier.
  final double glance;

  /// Rhythmic head bob amplitude (0 = none).
  final double bob;

  List<double> get values => [
    speed,
    amplitude,
    blinkMin,
    blinkMax,
    doubleBlink,
    breathRate,
    breathDepth,
    earTwitch,
    headTilt,
    bounce,
    energy,
    glance,
    bob,
    noseTwitch,
  ];

  static const SpeciesPersonality neutral = SpeciesPersonality();
}

/// Adding a species is one entry here; missing species fall back to [SpeciesPersonality.neutral].
SpeciesPersonality personalityFor(AvatarSpecies? species) =>
    speciesPersonalities[species] ?? SpeciesPersonality.neutral;

