#!/usr/bin/env bash
# =============================================================================
#  create_dmg.sh — BreakMate Complete Release Script
# =============================================================================
#
#  ONE COMMAND DOES EVERYTHING:
#    1. Flutter build macos --release
#    2. Package into BreakMate-Installer.dmg
#    3. Sign the DMG with Sparkle Ed25519 key
#    4. Create GitHub release + upload DMG + attach release notes
#    5. Update appcast.xml with real signature and file size
#    6. Commit and push appcast.xml to git
#
#  USAGE (from project root):
#    ./scripts/create_dmg.sh \
#        --version 1.2.0 \
#        --build 26 \
#        --notes-file release_notes.md
#
#    Or pass notes inline:
#    ./scripts/create_dmg.sh \
#        --version 1.2.0 \
#        --build 26 \
#        --notes "Bug fixes and performance improvements"
#
#  OPTIONAL FLAGS:
#    --skip-build    Skip flutter build (use existing build output)
#    --skip-github   Skip creating the GitHub release (just sign + appcast)
#    --dry-run       Show what would happen without touching anything
#
#  REQUIREMENTS:
#    - flutter (in PATH)
#    - create-dmg (brew install create-dmg)
#    - gh CLI (brew install gh) — logged in via: gh auth login
#    - Sparkle sign_update (bundled at macos/Pods/Sparkle/bin/sign_update)
#    - Private key: ~/secrets/breakmate_sparkle_private.pem
#      OR set env var: export SPARKLE_PRIVATE_KEY=/path/to/key.pem
#      (generate once with: ./scripts/generate_sparkle_keys.sh)
#
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

APP_NAME="BreakMate"
APP_BUILD_DIR="$PROJECT_ROOT/build/macos/Build/Products/Release-prod/${APP_NAME}.app"
DMG_OUTPUT_DIR="$PROJECT_ROOT/release_dmg"
DMG_NAME="${APP_NAME}-Installer.dmg"
DMG_PATH="$DMG_OUTPUT_DIR/$DMG_NAME"
APPCAST="$PROJECT_ROOT/appcast.xml"
GITHUB_REPO="bijithintersmart/standup"

# Default private key location (generated by generate_sparkle_keys.sh)
DEFAULT_PRIVATE_KEY="$HOME/secrets/breakmate_sparkle_private.pem"

# ── Colour helpers ─────────────────────────────────────────────────────────────
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m'; RESET='\033[0m'

info()    { echo -e "${CYAN}[INFO]${RESET}  $*"; }
success() { echo -e "${GREEN}[OK]${RESET}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${RESET}  $*"; }
error()   { echo -e "${RED}[ERROR]${RESET} $*" >&2; exit 1; }
step()    { echo -e "\n${BOLD}═══════════════════════════════════════${RESET}\n${BOLD}  $*${RESET}"; }

# ── Argument parsing ───────────────────────────────────────────────────────────
VERSION=""
BUILD_NUMBER=""
RELEASE_NOTES=""
NOTES_FILE=""
SKIP_BUILD=false
SKIP_GITHUB=false
DRY_RUN=false

usage() {
  echo ""
  echo -e "${BOLD}Usage:${RESET}"
  echo "  ./scripts/create_dmg.sh \\"
  echo "      --version 1.2.0 \\"
  echo "      --build 26 \\"
  echo "      --notes-file release_notes.md   (recommended)"
  echo ""
  echo "  OR with inline notes:"
  echo "  ./scripts/create_dmg.sh \\"
  echo "      --version 1.2.0 \\"
  echo "      --build 26 \\"
  echo "      --notes \"Bug fixes and improvements\""
  echo ""
  echo -e "${BOLD}Optional flags:${RESET}"
  echo "  --skip-build    Skip flutter build (use existing build)"
  echo "  --skip-github   Skip GitHub release creation"
  echo "  --dry-run       Show what would happen, touch nothing"
  echo ""
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --version)       VERSION="$2";        shift 2 ;;
    --build)         BUILD_NUMBER="$2";   shift 2 ;;
    --notes)         RELEASE_NOTES="$2";  shift 2 ;;
    --notes-file)    NOTES_FILE="$2";     shift 2 ;;
    --skip-build)    SKIP_BUILD=true;     shift   ;;
    --skip-github)   SKIP_GITHUB=true;    shift   ;;
    --dry-run)       DRY_RUN=true;        shift   ;;
    -h|--help)       usage ;;
    *) error "Unknown argument: $1. Run with --help for usage." ;;
  esac
done

# ── Validate ───────────────────────────────────────────────────────────────────
[[ -z "$VERSION" ]]      && error "--version is required (e.g. 1.2.0)."
[[ -z "$BUILD_NUMBER" ]] && error "--build is required (e.g. 26)."

# Resolve release notes: file takes priority over inline --notes
if [[ -n "$NOTES_FILE" ]]; then
  [[ ! -f "$NOTES_FILE" ]] && error "Notes file not found: $NOTES_FILE"
  RELEASE_NOTES="$(cat "$NOTES_FILE")"
  info "Release notes loaded from: $NOTES_FILE"
fi

[[ -z "$RELEASE_NOTES" ]] && error "Either --notes or --notes-file is required."

# Resolve private key
PRIVATE_KEY_PATH="${SPARKLE_PRIVATE_KEY:-}"
if [[ -z "$PRIVATE_KEY_PATH" && -f "$DEFAULT_PRIVATE_KEY" ]]; then
  PRIVATE_KEY_PATH="$DEFAULT_PRIVATE_KEY"
fi

# ── Print plan ─────────────────────────────────────────────────────────────────
echo ""
echo -e "${GREEN}${BOLD}╔════════════════════════════════════════════════════╗${RESET}"
echo -e "${GREEN}${BOLD}║   BreakMate Release Pipeline v${VERSION}${RESET}"  ║
echo -e "${GREEN}${BOLD}╚════════════════════════════════════════════════════╝${RESET}"
echo ""
echo -e "  Version:     ${BOLD}${VERSION}${RESET}  (build ${BUILD_NUMBER})"
echo -e "  DMG:         ${CYAN}${DMG_PATH}${RESET}"
echo -e "  GitHub repo: ${CYAN}${GITHUB_REPO}${RESET}"
echo -e "  appcast:     ${CYAN}${APPCAST}${RESET}"
if [[ -n "$PRIVATE_KEY_PATH" ]]; then
  echo -e "  Private key: ${CYAN}${PRIVATE_KEY_PATH}${RESET}"
else
  echo -e "  Private key: ${YELLOW}macOS Keychain (auto)${RESET}"
fi
[[ "$DRY_RUN" == true ]] && echo -e "  ${YELLOW}DRY-RUN mode — nothing will be changed${RESET}"
echo ""

# ── Prerequisites check ────────────────────────────────────────────────────────
step "Checking prerequisites"

check_tool() {
  local tool="$1"
  local install_hint="$2"
  if ! command -v "$tool" &>/dev/null; then
    error "$tool is not installed. $install_hint"
  fi
  success "$tool found."
}

export PATH="/opt/homebrew/bin:$PATH"
check_tool "flutter"    "Install from https://flutter.dev"
check_tool "appdmg"     "Run: npm install -g appdmg"
[[ "$SKIP_GITHUB" == false ]] && check_tool "gh" "Run: brew install gh && gh auth login"

# Verify gh is authenticated
if [[ "$SKIP_GITHUB" == false && "$DRY_RUN" == false ]]; then
  if ! gh auth status &>/dev/null; then
    error "GitHub CLI not authenticated. Run: gh auth login"
  fi
  success "GitHub CLI authenticated."
fi

# Check sign_update
SIGN_UPDATE="$PROJECT_ROOT/macos/Pods/Sparkle/bin/sign_update"
if [[ ! -x "$SIGN_UPDATE" ]]; then
  # Search fallbacks
  for candidate in "$PROJECT_ROOT/scripts/sign_update" "/usr/local/bin/sign_update" "/opt/homebrew/bin/sign_update"; do
    if [[ -x "$candidate" ]]; then SIGN_UPDATE="$candidate"; break; fi
  done
  # Search DerivedData
  if [[ ! -x "$SIGN_UPDATE" ]]; then
    DERIVED=$(find ~/Library/Developer/Xcode/DerivedData -name "sign_update" -type f 2>/dev/null | head -1)
    [[ -n "$DERIVED" ]] && SIGN_UPDATE="$DERIVED"
  fi
fi
[[ ! -x "$SIGN_UPDATE" ]] && error "sign_update not found. Run 'pod install' in macos/ first."
success "sign_update found at: $SIGN_UPDATE"

# ── STEP 1: Flutter build ──────────────────────────────────────────────────────
step "Step 1 of 5 — Flutter build"

if [[ "$SKIP_BUILD" == true ]]; then
  info "Skipping build (--skip-build flag)."
  [[ ! -d "$APP_BUILD_DIR" ]] && error "No build found at $APP_BUILD_DIR. Remove --skip-build."
else
  if [[ "$DRY_RUN" == true ]]; then
    warn "[DRY-RUN] Would run:  flutter build macos --flavor prod --release"
  else
    cd "$PROJECT_ROOT"
     flutter build macos --flavor prod --release
    success "Flutter build complete."
  fi
fi

# ── STEP 2: Create DMG ─────────────────────────────────────────────────────────
step "Step 2 of 5 — Package DMG"

mkdir -p "$DMG_OUTPUT_DIR"

if [[ -f "$DMG_PATH" ]]; then
  info "Removing existing DMG..."
  [[ "$DRY_RUN" == false ]] && rm -f "$DMG_PATH"
fi

if [[ "$DRY_RUN" == true ]]; then
  warn "[DRY-RUN] Would create DMG at $DMG_PATH"
else
  cd "$PROJECT_ROOT"
  appdmg scripts/appdmg.json "$DMG_PATH"
  success "DMG created: $DMG_PATH"
fi

# ── STEP 3: Sign the DMG ───────────────────────────────────────────────────────
step "Step 3 of 5 — Sign DMG with Sparkle Ed25519"

if [[ "$DRY_RUN" == true ]]; then
  warn "[DRY-RUN] Would sign $DMG_PATH"
  SIGNATURE="DRY_RUN_SIGNATURE"
  FILE_SIZE="12345678"
else
  SIGN_CMD=("$SIGN_UPDATE" "$DMG_PATH")
  [[ -n "$PRIVATE_KEY_PATH" ]] && SIGN_CMD+=(--ed-key-file "$PRIVATE_KEY_PATH")

  info "Running: ${SIGN_CMD[*]}"
  SIGN_OUTPUT=$("${SIGN_CMD[@]}" 2>&1) \
    || error "sign_update failed:\n$SIGN_OUTPUT"

  SIGNATURE=$(echo "$SIGN_OUTPUT" | grep -oE 'sparkle:edSignature="[^"]+"' | sed 's/sparkle:edSignature="//;s/"$//')
  FILE_SIZE=$(echo  "$SIGN_OUTPUT" | grep -oE 'length="[0-9]+"'             | sed 's/length="//;s/"$//')

  [[ -z "$SIGNATURE" ]] && error "Could not parse edSignature from:\n$SIGN_OUTPUT"
  [[ -z "$FILE_SIZE" ]] && FILE_SIZE=$(stat -f%z "$DMG_PATH")

  success "Signature: ${SIGNATURE:0:28}…"
  success "File size: $FILE_SIZE bytes"
fi

# ── STEP 4: Create GitHub Release + upload DMG ────────────────────────────────
step "Step 4 of 5 — GitHub Release"

TAG="v${VERSION}"
GITHUB_RELEASE_URL="https://github.com/${GITHUB_REPO}/releases/download/${TAG}/${DMG_NAME}"

if [[ "$SKIP_GITHUB" == true ]]; then
  info "Skipping GitHub release (--skip-github flag)."
elif [[ "$DRY_RUN" == true ]]; then
  warn "[DRY-RUN] Would create GitHub release $TAG and upload $DMG_PATH"
else
  # Delete existing release/tag if it exists (safe re-run)
  if gh release view "$TAG" --repo "$GITHUB_REPO" &>/dev/null; then
    info "Release $TAG already exists — deleting and recreating..."
    gh release delete "$TAG" --repo "$GITHUB_REPO" --yes
    git tag -d "$TAG" 2>/dev/null || true
    git push origin ":refs/tags/$TAG" 2>/dev/null || true
  fi

  # Create the release with the notes and upload the DMG
  gh release create "$TAG" \
    --repo "$GITHUB_REPO" \
    --title "BreakMate v${VERSION}" \
    --notes "$RELEASE_NOTES" \
    "$DMG_PATH"

  success "GitHub release $TAG created and DMG uploaded."
  info "Release URL: https://github.com/${GITHUB_REPO}/releases/tag/${TAG}"
fi

# ── STEP 5: Update appcast.xml ─────────────────────────────────────────────────
step "Step 5 of 5 — Update appcast.xml"

PUB_DATE=$(date -u +"%a, %d %b %Y %H:%M:%S +0000")
NOTES_HTML=$(echo "$RELEASE_NOTES" | sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g')
DOWNLOAD_URL="$GITHUB_RELEASE_URL"

PATCH_SCRIPT=$(cat <<'PYEOF'
import sys, re

appcast_path = sys.argv[1]
version      = sys.argv[2]
build        = sys.argv[3]
signature    = sys.argv[4]
file_size    = sys.argv[5]
download_url = sys.argv[6]
pub_date     = sys.argv[7]
notes_html   = sys.argv[8]
dry_run      = sys.argv[9] == "true"

with open(appcast_path, "r", encoding="utf-8") as f:
    content = f.read()

version_exists = bool(re.search(rf'sparkle:shortVersionString="{re.escape(version)}"', content))

if version_exists:
    print(f"[PATCH] Updating existing v{version} entry — signature + length.")
    # Patch sig
    content = re.sub(
        r'(sparkle:shortVersionString="' + re.escape(version) + r'"[^>]*?)sparkle:edSignature="[^"]*"',
        r'\g<1>' + f'sparkle:edSignature="{signature}"',
        content, flags=re.DOTALL
    )
    # Patch length
    content = re.sub(
        r'(sparkle:shortVersionString="' + re.escape(version) + r'"[^>]*?)length="[^"]*"',
        r'\g<1>' + f'length="{file_size}"',
        content, flags=re.DOTALL
    )
    new_content = content
else:
    print(f"[PATCH] Inserting new v{version} entry at top of feed.")
    new_item = f"""\
        <item>
            <title>Version {version}</title>
            <pubDate>{pub_date}</pubDate>
            <description><![CDATA[
                <h3>BreakMate v{version}</h3>
                <p>{notes_html}</p>
                <h4>Installation Note (macOS)</h4>
                <p>Since BreakMate is not notarized by Apple, macOS may show a security
                warning on first launch. Open System Settings &gt; Privacy and Security
                and click Allow Anyway next to BreakMate.</p>
            ]]></description>
            <enclosure url="{download_url}"
                       sparkle:version="{build}"
                       sparkle:shortVersionString="{version}"
                       sparkle:edSignature="{signature}"
                       length="{file_size}"
                       type="application/octet-stream" />
        </item>
"""
    m = re.search(r'<language>[^<]+</language>\s*', content)
    if m:
        new_content = content[:m.end()] + new_item + content[m.end():]
    else:
        new_content = content.replace("</channel>", new_item + "    </channel>")

if dry_run:
    print("[DRY-RUN] appcast.xml preview:")
    print(new_content[:1500])
else:
    with open(appcast_path, "w", encoding="utf-8") as f:
        f.write(new_content)
    print("[OK] appcast.xml patched.")
PYEOF
)

python3 - \
  "$APPCAST" "$VERSION" "$BUILD_NUMBER" \
  "$SIGNATURE" "$FILE_SIZE" "$DOWNLOAD_URL" \
  "$PUB_DATE" "$NOTES_HTML" "$DRY_RUN" \
  <<< "$PATCH_SCRIPT"

# Commit and push appcast.xml
if [[ "$DRY_RUN" == false ]]; then
  cd "$PROJECT_ROOT"
  if ! git diff --quiet "$APPCAST" 2>/dev/null; then
    git add "$APPCAST"
    git commit -m "chore: update appcast.xml for v${VERSION} release"
    git push origin main
    success "appcast.xml committed and pushed."
  else
    info "appcast.xml unchanged — nothing to commit."
  fi
fi

# ── Final summary ──────────────────────────────────────────────────────────────
echo ""
echo -e "${GREEN}${BOLD}╔═════════════════════════════════════════════════════╗${RESET}"
echo -e "${GREEN}${BOLD}║   BreakMate v${VERSION} — Release complete!${RESET}"
echo -e "${GREEN}${BOLD}╚═════════════════════════════════════════════════════╝${RESET}"
echo ""
echo -e "  ${BOLD}Version:${RESET}  $VERSION  (build $BUILD_NUMBER)"
echo -e "  ${BOLD}DMG:${RESET}      $DMG_PATH"
if [[ "$SKIP_GITHUB" == false ]]; then
echo -e "  ${BOLD}GitHub:${RESET}   https://github.com/${GITHUB_REPO}/releases/tag/${TAG}"
fi
echo -e "  ${BOLD}appcast:${RESET}  $APPCAST"
echo ""
echo -e "  Users with Sparkle auto-update will receive v${VERSION} automatically."
echo ""
